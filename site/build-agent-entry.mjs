#!/usr/bin/env node
import { readFile, writeFile, mkdir } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const skill = await read("skills/popcorn-temporal-anchor/SKILL.md");
if (skill !== await read("openclaw/popcorn-temporal-anchor/SKILL.md")) {
  throw new Error("Canonical and OpenClaw skills differ; synchronize before building.");
}
const assets = {};
async function add(paths, file, type) {
  const asset = { body: await read(file), type };
  for (const path of paths) assets[path] = asset;
}
await add(["/agents", "/agents/"], "site/agents/index.html", "text/html; charset=utf-8");
await add(["/demo", "/demo/"], "site/demo/index.html", "text/html; charset=utf-8");
await add(["/demo/styles.css"], "site/demo/styles.css", "text/css; charset=utf-8");
await add(["/demo/demo.js"], "site/demo/demo.js", "text/javascript; charset=utf-8");
await add(["/SKILL.md"], "skills/popcorn-temporal-anchor/SKILL.md", "text/markdown; charset=utf-8");
await add(["/llms.txt"], "site/llms.txt", "text/markdown; charset=utf-8");
await add(["/docs/temporal-usage.md"], "docs/TEMPORAL_USAGE.md", "text/markdown; charset=utf-8");
for (const name of ["evaluation-packet.production.json", "evaluation-packet.proceed-002.production.json", "evaluation-outcomes.json"]) {
  await add([`/samples/${name}`], `examples/witness/${name}`, "application/json; charset=utf-8");
}
const paths = ["/", "/time", "/agents", "/demo", "/lab-record", "/SKILL.md", "/llms.txt", "/agent/offer", "/openapi.json", "/.well-known/agent.json", "/.well-known/popcorn-keys.json", "/docs/temporal-usage.md", "/schemas/execution-schedule.v1.json", "/schemas/witness-request.v1.json", "/schemas/witness-response.v1.json", ...Object.keys(assets).filter(path => path.startsWith("/samples/"))];
assets["/sitemap.xml"] = {
  type: "application/xml; charset=utf-8",
  body: '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + paths.map(path => `  <url><loc>https://767-2676.com${path}</loc></url>`).join("\n") + "\n</urlset>\n",
};
const runtime = await read("site/agent-entry-runtime.mjs");
await mkdir(new URL("site/generated/", root), { recursive: true });
await writeFile(new URL("site/generated/agent-entry.mjs", root),
  '// Generated by node site/build-agent-entry.mjs. Do not edit.\n' +
  `const assets = ${JSON.stringify(assets, null, 2)};\n\n` + runtime +
  '\nexport const handleAgentEntry = createAgentEntryHandler(assets);\n');
console.log(`Built ${Object.keys(assets).length} free routes; no operational endpoints replaced.`);
